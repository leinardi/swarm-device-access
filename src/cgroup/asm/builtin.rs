//! The names `github.com/cilium/ebpf/asm` (v0.22.0) prints for a `BuiltinFunc`: the Linux helper
//! IDs 0 to 211 and the Windows ones, which carry the Windows platform tag in bits 28 to 30. The
//! lists were printed by a Go program from `asm.BuiltinFunc(id).String()`; any other ID prints as
//! `BuiltinFunc(<id>)`.

/// The first Windows helper ID: the Windows platform tag with helper 1.
const WINDOWS_FIRST: u32 = 0x1000_0001;

/// `asm.BuiltinFunc(id).String()`.
pub(super) fn name(id: u32) -> String {
    let known = usize::try_from(id)
        .ok()
        .and_then(|index| LINUX.get(index))
        .or_else(|| {
            id.checked_sub(WINDOWS_FIRST)
                .and_then(|index| usize::try_from(index).ok())
                .and_then(|index| WINDOWS.get(index))
        });
    known.map_or_else(|| format!("BuiltinFunc({id})"), |&name| name.to_owned())
}

